create table venue (
    id            bigint generated by default as identity primary key,
    slug          varchar(64)  not null unique,
    city          varchar(100) not null,
    name          varchar(200) not null,
    indoor        boolean      not null,
    address       varchar(300) not null,
    latitude      double precision not null,
    longitude     double precision not null,
    min_headcount integer      not null,
    max_headcount integer      not null,
    active        boolean      not null default true,
    constraint venue_headcount_range check (min_headcount > 0 and min_headcount <= max_headcount)
);

create table customer (
    id         bigint generated by default as identity primary key,
    name       varchar(200) not null,
    email      varchar(200) not null unique,
    phone      varchar(30)  not null,
    created_at timestamp with time zone not null
);

create table booking (
    id          bigint generated by default as identity primary key,
    venue_id    bigint      not null references venue (id),
    customer_id bigint      not null references customer (id),
    play_date   date        not null,
    start_time  time        not null,
    end_time    time        not null,
    headcount   integer     not null check (headcount > 0),
    note        varchar(1000),
    status      varchar(20) not null,
    created_at  timestamp with time zone not null,
    updated_at  timestamp with time zone not null,
    constraint booking_status_valid check (status in ('PENDING', 'ACCEPTED', 'REJECTED', 'CANCELLED'))
);

create index booking_venue_day on booking (venue_id, play_date);
create index booking_status on booking (status);

create table admin_user (
    id            bigint generated by default as identity primary key,
    username      varchar(100) not null unique,
    password_hash varchar(100) not null,
    enabled       boolean      not null default true,
    created_at    timestamp with time zone not null
);
