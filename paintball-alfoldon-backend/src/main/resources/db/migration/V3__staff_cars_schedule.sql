-- Staff, cars and the daily schedule (beosztás) of the admin dashboard.

create table employee (
    id              bigint generated by default as identity primary key,
    name            varchar(200) not null,
    phone           varchar(30),
    employment_type varchar(20)  not null,
    active          boolean      not null default true,
    constraint employee_type_valid check (employment_type in ('FULL_TIME', 'ON_CALL'))
);

-- Days an employee cannot work (szabadság, nem ér rá), both ends inclusive.
create table employee_exclusion (
    id          bigint generated by default as identity primary key,
    employee_id bigint       not null references employee (id) on delete cascade,
    date_from   date         not null,
    date_to     date         not null,
    reason      varchar(300),
    constraint employee_exclusion_range check (date_from <= date_to)
);

create index employee_exclusion_dates on employee_exclusion (date_from, date_to);

create table car (
    id     bigint generated by default as identity primary key,
    plate  varchar(20) not null unique,
    seats  integer     not null check (seats > 0),
    active boolean     not null default true
);

-- The assignment of a game: one car and the employees who go with it.
alter table booking add column car_id bigint;
alter table booking add constraint booking_car_fk foreign key (car_id) references car (id);

create table booking_employee (
    booking_id  bigint not null references booking (id) on delete cascade,
    employee_id bigint not null references employee (id),
    primary key (booking_id, employee_id)
);

-- Travel time from the base (Szeged) and the time needed to set up and pack up the field.
alter table venue add column travel_minutes integer not null default 0;
alter table venue add column setup_minutes integer not null default 45;
alter table venue add column teardown_minutes integer not null default 30;

-- Estimated from the coordinates: straight-line distance from Szeged x 1.3 at 60 km/h, at least 15 minutes.
-- Editable per venue on the dashboard (Pályák).
update venue set travel_minutes = 15 where slug in ('szeged', 'szeged-csarnok');
update venue set travel_minutes = 65 where slug = 'szentes';
update venue set travel_minutes = 135 where slug = 'szolnok';
update venue set travel_minutes = 105 where slug = 'kecskemet';
update venue set travel_minutes = 125 where slug = 'bekescsaba';
update venue set travel_minutes = 70 where slug = 'oroshaza';

-- A period when a venue cannot be booked (karbantartás, rendezvény...). Local Budapest time.
create table venue_block (
    id        bigint generated by default as identity primary key,
    venue_id  bigint    not null references venue (id) on delete cascade,
    starts_at timestamp not null,
    ends_at   timestamp not null,
    reason    varchar(300),
    constraint venue_block_range check (starts_at < ends_at)
);

create index venue_block_venue on venue_block (venue_id, starts_at);
